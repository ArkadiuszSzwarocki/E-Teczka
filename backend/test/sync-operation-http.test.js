const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const express = require('express');
const { PrismaClient } = require('@prisma/client');
const { createSyncRouter } = require('../routes/sync.js');

test('folder sync endpoint safely replays an operation and rejects a foreign parent', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'eteczka-http-test-'));
  const db = path.join(dir, 'test.db').replace(/\\/g, '/');
  const prisma = new PrismaClient({ datasources: { db: { url: `file:${db}` } } });
  let server;
  try {
    await prisma.$executeRawUnsafe("CREATE TABLE Subscription (id INTEGER PRIMARY KEY,ownerKey TEXT UNIQUE NOT NULL,provider TEXT NOT NULL DEFAULT 'stripe',providerCustomerId TEXT,providerSubscriptionId TEXT,plan TEXT NOT NULL DEFAULT 'free',status TEXT NOT NULL DEFAULT 'inactive',currentPeriodEnd DATETIME,cancelAtPeriodEnd BOOLEAN NOT NULL DEFAULT 0,createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP)");
    await prisma.$executeRawUnsafe('CREATE TABLE "SyncOperation" ("ownerKey" TEXT NOT NULL, "operationId" TEXT NOT NULL, "result" TEXT NOT NULL, "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY ("ownerKey", "operationId"))');
    await prisma.$executeRawUnsafe('CREATE TABLE "Folder" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "name" TEXT NOT NULL, "parentId" INTEGER, "ownerId" INTEGER NOT NULL, "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, "order" INTEGER NOT NULL DEFAULT 0, "updatedAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP)');
    await prisma.$executeRawUnsafe('CREATE TABLE "Document" ("id" INTEGER PRIMARY KEY AUTOINCREMENT, "title" TEXT NOT NULL, "filePath" TEXT NOT NULL, "mimeType" TEXT NOT NULL, "folderId" INTEGER NOT NULL, "userId" INTEGER, "thumbnail" TEXT, "ocrText" TEXT, "retentionEnabled" BOOLEAN NOT NULL DEFAULT 1, "retentionValue" INTEGER NOT NULL DEFAULT 5, "retentionUnit" TEXT NOT NULL DEFAULT \'years\', "isArchived" BOOLEAN NOT NULL DEFAULT 0, "isDeleted" BOOLEAN NOT NULL DEFAULT 0, "deletedAt" DATETIME, "physicalLocation" TEXT, "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP)');
    await prisma.$executeRaw`INSERT INTO Folder (name, ownerId) VALUES ('foreign', 2)`;
    const app = express();
    app.use(express.json());
    app.use('/api/sync', createSyncRouter(prisma));
    server = await new Promise(resolve => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)); });
    const url = `http://127.0.0.1:${server.address().port}/api/sync/operation`;
    const send = body => fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const body = { operationId: 'op-1', operation: { entity: 'folders', type: 'created', value: { clientId: 'c1', name: 'Nowa' } } };
    const first = await (await send(body)).json();
    const second = await (await send(body)).json();
    assert.equal(first.success, true);
    assert.equal(second.replayed, true);
    assert.equal(first.value.id, second.value.id);
    assert.equal((await prisma.$queryRaw`SELECT COUNT(*) AS count FROM Folder`)[0].count, 2n);
    const rename = { operationId: 'rename-1', operation: { entity: 'folders', type: 'updated', value: { id: first.value.id, name: 'Zmieniona', order: 2, updatedAt: '2099-01-01T00:00:00.000Z' } } };
    assert.equal((await (await send(rename)).json()).value.conflict, false);
    assert.equal((await (await send(rename)).json()).replayed, true);
    const renamed = await prisma.folder.findUnique({ where: { id: first.value.id } });
    assert.equal(renamed.name, 'Zmieniona');
    assert.equal(renamed.order, 2);
    const staleRename = { operationId: 'rename-old', operation: { ...rename.operation, value: { ...rename.operation.value, name: 'Stara', updatedAt: '2000-01-01T00:00:00.000Z' } } };
    assert.equal((await (await send(staleRename)).json()).value.conflict, true);
    assert.equal((await prisma.folder.findUnique({ where: { id: first.value.id } })).name, 'Zmieniona');
    await prisma.$executeRaw`INSERT INTO Document (title, filePath, mimeType, folderId) VALUES ('Test', 'test.pdf', 'application/pdf', ${first.value.id})`;
    const document = { id: 1, title: 'Test po zmianie', filePath: 'test.pdf', mimeType: 'application/pdf', folderId: first.value.id, retentionEnabled: false, retentionValue: 3, retentionUnit: 'months', isArchived: true, isDeleted: false, updatedAt: '2099-01-01T00:00:00.000Z' };
    const archive = { operationId: 'archive-1', operation: { entity: 'documents', type: 'updated', value: document } };
    const archived = await (await send(archive)).json();
    assert.equal(archived.value.conflict, false);
    assert.equal((await (await send(archive)).json()).replayed, true);
    const updated = await prisma.document.findUnique({ where: { id: 1 } });
    assert.equal(updated.isArchived, true);
    assert.equal(updated.title, 'Test po zmianie');
    assert.equal(updated.retentionEnabled, false);
    assert.equal(updated.retentionValue, 3);
    assert.equal(updated.retentionUnit, 'months');
    const conflict = await (await send({ operationId: 'archive-old', operation: { ...archive.operation, value: { ...document, isArchived: false, updatedAt: '2000-01-01T00:00:00.000Z' } } })).json();
    assert.equal(conflict.value.conflict, true);
    assert.equal((await prisma.document.findUnique({ where: { id: 1 } })).isArchived, true);
    await prisma.$executeRaw`INSERT INTO Document (title, filePath, mimeType, folderId) VALUES ('Obcy', 'foreign.pdf', 'application/pdf', 1)`;
    const foreign = await send({ operationId: 'foreign-doc', operation: { ...archive.operation, value: { ...document, id: 2, folderId: 1 } } });
    assert.equal(foreign.status, 409);
    assert.equal((await prisma.document.findUnique({ where: { id: 2 } })).isArchived, false);
    const denied = await send({ operationId: 'op-2', operation: { entity: 'folders', type: 'created', value: { clientId: 'c2', name: 'Nieuprawniona', parentId: 1 } } });
    assert.equal(denied.status, 409);
    assert.equal((await prisma.$queryRaw`SELECT COUNT(*) AS count FROM Folder`)[0].count, 2n);
    const nonempty = await send({ operationId: 'delete-nonempty', operation: { entity: 'folders', type: 'deleted', value: { id: first.value.id, updatedAt: '2099-01-01T00:00:00.000Z' } } });
    assert.equal(nonempty.status, 409);
    const createdEmpty = await (await send({ operationId: 'create-empty', operation: { entity: 'folders', type: 'created', value: { clientId: 'empty', name: 'Pusta' } } })).json();
    const staleDelete = await send({ operationId: 'delete-stale', operation: { entity: 'folders', type: 'deleted', value: { id: createdEmpty.value.id, updatedAt: '2000-01-01T00:00:00.000Z' } } });
    assert.equal(staleDelete.status, 409);
    assert.ok(await prisma.folder.findUnique({ where: { id: createdEmpty.value.id } }));
    const deleteEmpty = { operationId: 'delete-empty', operation: { entity: 'folders', type: 'deleted', value: { id: createdEmpty.value.id, updatedAt: '2099-01-01T00:00:00.000Z' } } };
    assert.equal((await (await send(deleteEmpty)).json()).success, true);
    assert.equal((await (await send(deleteEmpty)).json()).replayed, true);
    assert.equal(await prisma.folder.findUnique({ where: { id: createdEmpty.value.id } }), null);
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    await prisma.$disconnect();
    if (fs.existsSync(db)) fs.unlinkSync(db);
    fs.rmdirSync(dir);
  }
});
